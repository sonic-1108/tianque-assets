import { NodeIO } from '@gltf-transform/core';
import { ALL_EXTENSIONS } from '@gltf-transform/extensions';
import { textureCompress, resample, prune, meshopt, dedup } from '@gltf-transform/functions';
import { MeshoptEncoder } from 'meshoptimizer';
import sharp from 'sharp';
const [, , src, dst, keepCsv] = process.argv;
const keep = keepCsv.split(',');
await MeshoptEncoder.ready;
const io = new NodeIO().registerExtensions(ALL_EXTENSIONS).registerDependencies({ 'meshopt.encoder': MeshoptEncoder });
const doc = await io.read(src);
for (const a of doc.getRoot().listAnimations()) if (!keep.includes(a.getName().replace(/\.\d+$/, ''))) a.dispose();
await doc.transform(dedup(), resample(), prune(), textureCompress({ encoder: sharp, targetFormat: 'webp', resize: [1024, 1024], quality: 88 }), meshopt({ encoder: MeshoptEncoder, level: 'medium' }));
await io.write(dst, doc);
console.log('anims', doc.getRoot().listAnimations().map((a) => a.getName()).join(','));
